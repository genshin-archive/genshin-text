def main():
    con = sqlite3.connect(DB)
    cur = con.cursor()
    cur.executescript(SCHEMA)
    cur.executemany("INSERT INTO time_axes VALUES (?,?,?)", AXES)
    title2id = {}
    for i, (t, d, m, e, s, ax) in enumerate(E, 1):
        cur.execute("INSERT INTO events VALUES (?,?,?,?,?,?)", (i, t, d, m, e, s))
        title2id[t] = i
        for axis, pos in ax:
            cur.execute("INSERT INTO event_axis_map VALUES (?,?,?)", (i, axis, pos))
    for a, b, rel, note in L:
        cur.execute("INSERT INTO event_links (from_event,to_event,relation,note) VALUES (?,?,?,?)",
                    (title2id[a], title2id[b], rel, note))
    cur.executemany("INSERT INTO metaphors (metaphor,target,evidence_level,status) VALUES (?,?,?,?)", M)
    con.commit()
    print("axes:", cur.execute("SELECT COUNT(*) FROM time_axes").fetchone()[0])
    print("events:", cur.execute("SELECT COUNT(*) FROM events").fetchone()[0])
    print("axis_map:", cur.execute("SELECT COUNT(*) FROM event_axis_map").fetchone()[0])
    print("links:", cur.execute("SELECT COUNT(*) FROM event_links").fetchone()[0])
    print("metaphors:", cur.execute("SELECT COUNT(*) FROM metaphors").fetchone()[0])

if __name__ == "__main__":
    main()
